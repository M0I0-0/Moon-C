export const baseLang = (lang) => (typeof lang === 'string' && lang.toLowerCase().startsWith('en') ? 'en' : 'es')

/** Texto fijo en el idioma de la cuenta; {var} se sustituye con `vars`. */
export function tr(lang, key, vars) {
  const base = baseLang(lang)
  const text = DICT[base][key] ?? DICT.es[key] ?? key
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : text
}

/** Locale para fechas y horas. */
export const localeFor = (lang) => (baseLang(lang) === 'en' ? 'en-US' : 'es-MX')
