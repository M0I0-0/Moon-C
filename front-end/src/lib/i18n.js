const BASES = ['es', 'en', 'ru', 'de']
/** Idioma de interfaz soportado (es, en, ru, de); cualquier otro cae a es (idioma por defecto). */
export const baseLang = (lang) => {
  const b = typeof lang === 'string' ? lang.toLowerCase().slice(0, 2) : ''
  return BASES.includes(b) ? b : 'es'
}

/** Elige `obj[lang]` con respaldo a en y luego es (contenido de shared/*.json con ru/de aún incompleto). */
export const pickLang = (obj, lang) => obj?.[baseLang(lang)] ?? obj?.en ?? obj?.es

/** Texto fijo en el idioma de la cuenta; {var} se sustituye con `vars`. Falta la clave: en, luego es. */
export function tr(lang, key, vars) {
  const text = DICT[baseLang(lang)][key] ?? DICT.en[key] ?? DICT.es[key] ?? key
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : text
}

const LOCALES = { es: 'es-MX', en: 'en-US', ru: 'ru-RU', de: 'de-DE' }
/** Locale para fechas y horas. */
export const localeFor = (lang) => LOCALES[baseLang(lang)]
